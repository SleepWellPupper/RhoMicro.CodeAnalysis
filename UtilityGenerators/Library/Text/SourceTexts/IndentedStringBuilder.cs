    private Boolean LastWasNewLine
    {
        get
        {
            if(_builder.Length < Options.NewLine.Length)
                return false;

            for(var i = 1; i <= Options.NewLine.Length; i++)
            {
                if(_builder[^i] != Options.NewLine[^i])
                    return false;
            }

            return true;
        }
    }
