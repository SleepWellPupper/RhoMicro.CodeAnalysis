namespace RhoMicro.CodeAnalysis.UtilityGenerators.Tests.Library.Text.Templating;

using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

using RhoMicro.CodeAnalysis.Library.Models;
using RhoMicro.CodeAnalysis.Library.Text.Templating;

public partial class GeneratedFileTemplateTests
{
    [Fact]
    public void IncludesLicensingAndPragmasByDefault()
    {
        var actual = new GeneratedFileTemplate("Foo").ToString();
        Assert.Equal(
            """
            // <auto-generated>
            // This file was auto generated by the following tool: Foo.
            // The generator used to generate this file may be subject to a license.
            // This generated file is, however, not subject to that license.
            // Instead, it is subject to whatever licensing scheme is present in the project containing it.
            // </auto-generated>
            #pragma warning disable
            #nullable enable

            """, actual);
    }

    [Template(
        """
        Foo
        Bar
        Baz
        """)]
    internal readonly partial struct Body;

    [Fact]
    public void RendersBody()
    {
        var actual = new GeneratedFileTemplate("Foo").RenderToString(new Body());
        Assert.Equal(
            """
            // <auto-generated>
            // This file was auto generated by the following tool: Foo.
            // The generator used to generate this file may be subject to a license.
            // This generated file is, however, not subject to that license.
            // Instead, it is subject to whatever licensing scheme is present in the project containing it.
            // </auto-generated>
            #pragma warning disable
            #nullable enable
            Foo
            Bar
            Baz

            """, actual);
    }
}